// For undefined chars, use '?'
static uint8_t* get_glyph(char c) {
    unsigned char uc = (unsigned char)c;
    if(uc>127) c='?';
    int allzero=1;
    for(int i=0;i<8;i++) if(font8x8[(int)uc][i]!=0) allzero=0;
    if(allzero && uc!=' ') return font8x8[63];
    return font8x8[(int)uc];
}

void font_draw_char(int x, int y, char c, uint32_t fg, uint32_t bg) {
    uint8_t* glyph = get_glyph(c);
    for(int row=0; row<8; row++) {
        uint8_t bits = glyph[row];
        for(int col=0; col<8; col++) {
            uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
            // If bg is transparent (0xFFFFFFFF), skip bg pixels
            if(color==0xFFFFFFFF && !(bits & (0x80>>col))) continue;
            fb_put_pixel(x+col, y+row, color);
        }
    }
}

void font_draw_string(int x, int y, const char* str, uint32_t fg, uint32_t bg) {
    int cx=x;
    while(*str) {
        if(*str=='\n') { y+=10; cx=x; str++; continue; }
        font_draw_char(cx, y, *str, fg, bg);
        cx+=8;
        str++;
    }
}

void font_draw_string_scale(int x, int y, const char* str, uint32_t fg, int scale) {
    // Scale 2x etc
    int cx=x;
    while(*str) {
        if(*str=='\n') { y+=10*scale; cx=x; str++; continue; }
        uint8_t* glyph = get_glyph(*str);
        for(int row=0; row<8; row++) {
            uint8_t bits = glyph[row];
            for(int col=0; col<8; col++) {
                if(bits & (0x80>>col)) {
                    fb_fill_rect(cx+col*scale, y+row*scale, scale, scale, fg);
                }
            }
        }
        cx+=8*scale;
        str++;
    }
}
